/** "1 pm" in Hindi: part of day plus the 12-hour number, e.g. 13 -> "दोपहर 1 बजे". */
export function hiHour(h) {
  const h12 = h % 12 === 0 ? 12 : h % 12;
  const part = h < 4 ? 'रात' : h < 12 ? 'सुबह' : h < 17 ? 'दोपहर' : h < 20 ? 'शाम' : 'रात';
  return `${part} ${h12} बजे`;
}

